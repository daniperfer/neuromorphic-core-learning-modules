# Challenge 4: Evaluation and Benchmarking

"""
The field has developed event-based datasets — the N-MNIST,
N-Caltech101, and DSEC driving datasets, among others
— but these are still far smaller and less diverse than the
large-scale frame-based datasets that have driven deep learning progress.
"""

