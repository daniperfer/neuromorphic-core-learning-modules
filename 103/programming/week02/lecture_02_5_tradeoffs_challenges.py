# Worked Example: When to Use Event-Based vs. Frame-Based Vision

# Task 1: Counting pedestrians entering a store entrance over an 8-hour period.
"""
Scene: Mostly static. Pedestrians slowly walk past a camera that is fixed to a wall.
Frame-based is likely better. The motion events generated by pedestrians would
be useful, but texture and shape information (which event cameras can’t provide
in static moments) matter for accurately distinguishing people.
"""

# Task 2: Tracking a drone flying at 80 km/h through an obstacle course.
"""
Highly dynamic. Fast motion, changing lighting, millisecond-level events critical.
Event-based is better. The drone generates strong, fast edge events.
Latency below 1 ms is achievable.
"""

# Task 3: Reading a license plate on a parked car in a parking garage.
"""
Frame-based is clearly better. The event camera would produce zero events
for a parked car in static illumination.
"""
