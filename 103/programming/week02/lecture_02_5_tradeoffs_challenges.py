# ------------------
# Challenge 1: Noise

"""
Event-based sensors have a complex noise profile.
The consequence is that event-based algorithms must
explicitly handle noise — through temporal filtering
(discarding events that occur in isolation, without
neighboring events at similar times), spatial filtering
(requiring correlated events across adjacent pixels),
or statistical methods that treat the event stream as a
noisy channel. This adds algorithmic complexity.
"""

